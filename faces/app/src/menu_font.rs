pub(crate) fn horizontal_scale(scale: i32) -> i32 {
    ((scale.max(1) * 2 + 2) / 3).max(1)
}

pub(crate) fn advance(scale: i32) -> i32 {
    ADVANCE * horizontal_scale(scale)
}

pub(crate) fn text_width(text: &str, scale: i32) -> i32 {
    text.chars().count() as i32 * advance(scale)
}

pub(crate) fn draw_text(
    surface: &mut dyn Surface,
    text: &str,
    x: i32,
    y: i32,
    scale: i32,
    mark: char,
) {
    let vertical_scale = scale.max(1);
    let horizontal_scale = horizontal_scale(vertical_scale);
    let mut cursor_x = x;
    for character in text.chars() {
        for (row, bits) in glyph(character).iter().enumerate() {
            for column in 0..GLYPH_WIDTH {
                if bits & (1 << (GLYPH_WIDTH - 1 - column)) == 0 {
                    continue;
                }
                for offset_y in 0..vertical_scale {
                    for offset_x in 0..horizontal_scale {
                        surface.plot(
                            cursor_x + column * horizontal_scale + offset_x,
                            y + row as i32 * vertical_scale + offset_y,
                            mark,
                        );
                    }
                }
            }
        }
        cursor_x += ADVANCE * horizontal_scale;
    }
}

#[cfg(test)]
mod tests {
    use super::{advance, draw_text, text_width};
    use numinous_core::Canvas;

    #[test]
    fn cartridge_face_is_wide_monospaced_and_scales_in_whole_pixels() {
        assert_eq!(advance(1), 8);
        assert_eq!(advance(6), 32);
        assert_eq!(text_width("MENU", 6), 128);
    }

    #[test]
    fn cartridge_face_draws_distinct_solid_letters_and_punctuation() {
        let mut menu = Canvas::new(160, 48);
        draw_text(&mut menu, "QUIT: F / ALT+F4", 0, 0, 2, '#');
        assert!(menu.ink_count() > 100);

        let mut modern = Canvas::new(24, 16);
        let mut cartridge = Canvas::new(24, 16);
        numinous_core::draw_text(&mut modern, "M", 0, 0, 1, '#');
        draw_text(&mut cartridge, "M", 0, 0, 1, '#');
        assert_ne!(modern.to_text(), cartridge.to_text());
    }
}
